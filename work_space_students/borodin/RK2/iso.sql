CREATE VIEW rk.v_region_income_iso AS
SELECT
    i.period,
    i.year,
    i.month,
    i.object_name,
    iso.iso_code,
    i.budget_type,
    i.income_thousand_rub,
    i.income_billion_rub
FROM rk.v_region_income_long AS i
INNER JOIN rk.region_iso AS iso
    ON i.object_name = iso.object_name;